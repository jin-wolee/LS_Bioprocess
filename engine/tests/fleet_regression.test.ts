import { describe, expect, it } from "vitest";
import { runScenario } from "../src/run.ts";
import { logHash } from "../src/trace.ts";
import { readJson } from "./support/paths.ts";
import { configOf, SMALL } from "./support/scenarios.ts";
import type { Patch } from "./support/scenarios.ts";

// Spec section 4.5.5: with `bay_profiles` and `analyzer_profiles` absent every log is what it was. The default scenario is held by tests/golden (golden_default.test.ts).
// The other bundled scenarios have no golden file: their hashes below were taken at the base commit 69474c1, before the mixed-fleet change (seed 1; sc08 with feedback off,
// because the open loop is all S1 builds), and are pinned here, never regenerated by a script. The same numbers are the target of the "written out" form: a scenario that lists
// its own default profile in every position gives the same log as the scenario without the lists.

const hashOf = async (name: string, p?: Patch): Promise<string> => logHash(runScenario(configOf(name, p)).events);
const golden = (seed: number): string => readJson<{ log_hash: string }>("tests", "golden", `default_seed${seed}.summary.json`).log_hash;

const BEFORE = {
  sc02_shift_burst: "57eabcc537596057dcc078f98166ff06ba2900b76e25d4e89b24f48b761baa92",
  sc03_feed_in_gap: "3a45d38033d6cbfebf5bb953e409fc72fb0f1d0cef64c32d110b0ff19c865a1a",
  sc05_one_analyzer_down: "6a1d11ed9bbd6d10924f1d4edade1123bd673e86b3a65511d545374dbc9032a7",
  sc08_ph_restandardisation: "4c7e71c8c1fd354624743abea6202eea5351d0bc06cbcb4bdcef8d313b89b64b",
} as const;
/** Default scenario at the SMALL size, one profile switched, taken at the base commit. */
const SMALL_BEFORE = {
  split: "6e3766f57932dd45ff69296608373b6d2bc976788d0b7b6e09866788dca4c664",
  hplc: "76dbc7689a2d15b0d7bb2235cbdd2a7fb9d750abf485412149b173f680a1bf93",
  micro: "0b5f9d60b0b5bd9774cf896c959a91fc7fe937b9633c910ad81fe8c8f82228fe",
  pilot: "2151082ea134ca28efa223b35e62bd7d96562c03f6be33f631106c986fa853eb",
  trainee: "88e82df64756abc2c779db3be7e11ce350d85d23680783808e5f7319b2744640",
  split3: "14a5586e731b077f3d653b27e4b848df8d3f72c76be630807fe6fa996fc1a1e6",
} as const;

describe("Mixed fleets, regression: the lists absent change nothing", () => {
  it.each(Object.entries(BEFORE))("Given %s with no list When it runs Then its log hash is the one taken before the change", async (name, hash) => {
    expect(await hashOf(name, { feedback: false })).toBe(hash);
  });

  it.each([
    ["the split analyzer", { profiles: { analyzer: "split_cellcounter_metabolite" } }, SMALL_BEFORE.split],
    ["the HPLC as the analyzer", { profiles: { analyzer: "hplc" } }, SMALL_BEFORE.hplc],
    ["the micro-scale bioreactor", { profiles: { bioreactor: "micro_mini_parallel" } }, SMALL_BEFORE.micro],
    ["the pilot bioreactor", { profiles: { bioreactor: "pilot" } }, SMALL_BEFORE.pilot],
    ["the trainee staff", { profiles: { staff: "trainee" } }, SMALL_BEFORE.trainee],
  ] as [string, Patch, string][])("Given %s at the small size with no list Then the log hash is the one taken before the change", async (_label, patch, hash) => {
    expect(await hashOf("default", { ...patch, settings: SMALL })).toBe(hash);
  });

  it("Given three split analyzers (six instruments) with no list Then the log hash is the one taken before the change", async () => {
    expect(await hashOf("default", { profiles: { analyzer: "split_cellcounter_metabolite" }, settings: { ...SMALL, analyzer_count: 3 } })).toBe(SMALL_BEFORE.split3);
  });
});

describe("Mixed fleets, regression: the lists written out with the defaults give the same log", () => {
  it.each([1, 2, 3])("Given the default scenario with both lists written out (two bays of bench_manual, two all-in-one analyzers) and seed %i Then the log hash is the golden's", async (seed) => {
    const written = await hashOf("default", { seed, fields: { bay_profiles: ["bench_manual", "bench_manual"], analyzer_profiles: ["allinone_atline", "allinone_atline"] } as never });
    expect(written).toBe(golden(seed));
  });

  it("Given the split analyzer as profiles.analyzer and the list [split, split] Then the log hash is that of the scenario without the list", async () => {
    const list = ["split_cellcounter_metabolite", "split_cellcounter_metabolite"];
    expect(await hashOf("default", { profiles: { analyzer: "split_cellcounter_metabolite" }, settings: SMALL, fields: { analyzer_profiles: list } as never })).toBe(SMALL_BEFORE.split);
  });

  it("Given the HPLC as profiles.analyzer (its stability entries then name analytes it does not measure) and the list [hplc, hplc] Then the load passes and the log is unchanged", async () => {
    expect(await hashOf("default", { profiles: { analyzer: "hplc" }, settings: SMALL, fields: { analyzer_profiles: ["hplc", "hplc"] } as never })).toBe(SMALL_BEFORE.hplc);
  });

  it("Given the micro-scale profile as profiles.bioreactor and bay_profiles written out (one bay at the small size) Then the log is unchanged", async () => {
    expect(await hashOf("default", { profiles: { bioreactor: "micro_mini_parallel" }, settings: SMALL, fields: { bay_profiles: ["micro_mini_parallel"] } as never })).toBe(SMALL_BEFORE.micro);
  });

  it("Given the pilot profile as profiles.bioreactor and bay_profiles written out Then the log is unchanged", async () => {
    expect(await hashOf("default", { profiles: { bioreactor: "pilot" }, settings: SMALL, fields: { bay_profiles: ["pilot"] } as never })).toBe(SMALL_BEFORE.pilot);
  });
});
