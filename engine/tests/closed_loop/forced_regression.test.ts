import { describe, expect, it } from "vitest";
import { evaluationSettings } from "../../src/evaluate/config.ts";
import { runClosedLoopSeed } from "../../src/experiments/assembly/closed_loop.ts";
import type { ClosedLoopInput } from "../../src/experiments/assembly/closed_loop.ts";
import { buildShared } from "../../src/experiments/assembly/closed_loop_shared.ts";
import { createRng } from "../../src/rng.ts";
import { runScenario } from "../../src/run.ts";
import { loadScenario } from "../../src/scenario.ts";
import { logHash } from "../../src/trace.ts";
import { loadClosedLoop } from "../support/experiment2.ts";
import { withoutNewFlags } from "../support/break_out_pin.ts";
import { PRESETS } from "../support/open_loop_setup.ts";
import { readJson } from "../support/paths.ts";
import { SMALL, lookup, patched, rawScenario } from "../support/scenarios.ts";

// S3d: a forced plant in the closed loop. With no plant, every output of experiment 2 stays what it was (the condition of the S3a2 review). The hashes below were taken at the base
// commit 0c20da1, before any change of S3d (the outcome of a seed as canonical JSON, the recorded dataset each architecture's arm reads, the lab run's reactors and samples), and are
// pinned here, never regenerated by a script. They are a characterisation: green at once by design. A recorded dataset carries the flags of its architecture, so since the ninth and tenth flags
// (ADR-0017, ADR-0020; spec 11.8.4 regression rule) it is hashed with those two keys removed, which is the form the hashes were taken in; every other byte is what it was. The full-size seed is the first of scenarios/experiments/experiment2.json.

const EVAL = evaluationSettings(readJson("scenarios", "evaluation", "default.json"));
const BEFORE = {
  small_seed_3_outcome: "99512d9ffdab2bfc236143322e3e32435ce1e1e6b9c5f5125fffa91026bc3665",
  small_seed_4_outcome: "c6e077ecd114a16047076541c8fae61fc59d91ac3d37eeebb273d043976c35ea",
  small_seed_3_record_a_manual: "60f975b2563a081aae4e4c445c27c6cbd18a862acbe5a0fef9086fb6ef0e8056",
  small_seed_3_record_b_lims_lite: "02ae30789d4c9333ac04eaead86965c98e5975301534ea6ba01418362f5736f1",
  small_seed_3_record_c_context: "9e9573d1286f437fe20289e2eb44fe4f49a7f043556bce674214e26cf7ab8bcd",
  small_seed_3_reactors: "0e05e088829e71c34640a467c0d68b97c09632fcfbfdc5c976adac741aa4d01d",
  full_seed_5113_outcome: "54c313321cb29a99c62ff502c71d42f3b213de81d6feb69731888a105efff8f5",
} as const;

const scenario = loadScenario(patched(rawScenario("sc08_ph_restandardisation"), { settings: SMALL }), lookup);
const small = (): ClosedLoopInput => ({
  scenario, seeds: [3, 4], evaluation: EVAL, architectures: PRESETS, variants: [{ id: "c_context_modelled", of: "c_context", bias_handling: "model" }],
});
const sharedOf = (forced?: ClosedLoopInput["forced"]) => {
  const run = runScenario({ ...scenario, seed: 3, feedback: false });
  return buildShared(run, scenario, 3, { architectures: PRESETS, evaluation: EVAL, rng: createRng(), ...(forced && { forced }) });
};
const datasetOf = (sh: ReturnType<typeof sharedOf>, id: string) => withoutNewFlags(sh.structure[id]?.dataset as NonNullable<(typeof sh.structure)[string]>["dataset"]);
const reactorsOf = (sh: ReturnType<typeof sharedOf>) => sh.reactors.map((r) => ({ unit_id: r.unit_id, t0_s: r.t0_s, cadence_s: r.cadence_s, noise: Array.from(r.noise), samples: r.samples }));

describe("Experiment 2 with no plant: every output is what it was before the forced input existed", () => {
  it.each([3, 4])("Given the small SC8 scenario, seed %i and no plant Then the outcome of every arm hashes to the value taken before the change", async (seed) => {
    expect(await logHash([runClosedLoopSeed(small(), seed)])).toBe(BEFORE[`small_seed_${seed}_outcome` as keyof typeof BEFORE]);
  });

  it("Given seed 3 and no plant Then the recorded dataset each architecture's arm reads and the lab run's reactors hash to the values taken before the change", async () => {
    const sh = sharedOf();
    expect(await logHash([datasetOf(sh, "a_manual")])).toBe(BEFORE.small_seed_3_record_a_manual);
    expect(await logHash([datasetOf(sh, "b_lims_lite")])).toBe(BEFORE.small_seed_3_record_b_lims_lite);
    expect(await logHash([datasetOf(sh, "c_context")])).toBe(BEFORE.small_seed_3_record_c_context);
    expect(await logHash([reactorsOf(sh)])).toBe(BEFORE.small_seed_3_reactors);
  });

  it("Given the full-size scenario of experiment 2, its first seed and no plant Then the outcome of every arm hashes to the value taken before the change", async () => {
    const { input } = loadClosedLoop(readJson("scenarios", "experiments", "experiment2.json"));
    expect(input.seeds[0]).toBe(5113);
    expect(await logHash([runClosedLoopSeed(input, 5113)])).toBe(BEFORE.full_seed_5113_outcome);
  });

  it("Given an empty plant list (forced: []) Then it is no plant: the same hashes, the injector does not run", async () => {
    expect(await logHash([runClosedLoopSeed({ ...small(), forced: [] }, 3)])).toBe(BEFORE.small_seed_3_outcome);
    const sh = sharedOf([]);
    expect(await logHash([datasetOf(sh, "a_manual")])).toBe(BEFORE.small_seed_3_record_a_manual);
    expect(await logHash([datasetOf(sh, "c_context")])).toBe(BEFORE.small_seed_3_record_c_context);
    expect(await logHash([reactorsOf(sh)])).toBe(BEFORE.small_seed_3_reactors);
  });

  it("Given no plant Then no arm outcome carries a decision log: the key is absent, not empty", () => {
    for (const arm of runClosedLoopSeed(small(), 3).arms) expect(Object.keys(arm), arm.id).toEqual(["id", "kind", "reactors", "counts"]);
  });
});
