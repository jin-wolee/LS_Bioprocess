// The pins of the ninth and tenth flags (ADR-0017, ADR-0020; spec 11.8.4 regression rule, 11.8.5 batch 1): the recorded datasets, the metrics cells and the report blocks of the
// eleven architectures that existed before the two flags, for the small default scenario. The values in break_out_flags_pin.test.ts were taken at the base commit 81b83f2 with
// this module, before any engine code changed, and are never regenerated by a script.

/** The eight flags of ADR-0005, typed here so that the eleven stay the eleven when the flag list grows. */
export const EIGHT: readonly FlagName[] = [
  "system_issued_id", "two_clocks", "available_at", "instrument_state_snapshot", "append_only_versions", "write_time_keys", "ingest_idempotency", "audit_trail",
];
/** The two flags the pins do not see: a dataset is compared with these two keys removed. */
export const NEW_FLAGS = ["material_lot_links", "equipment_links"] as const;

const preset = (name: string): Architecture => parseArchitecture(readJson("scenarios", "architectures", `${name}.json`));
export const C: Architecture = preset("c_context");
/** A, B, C and C minus each of the eight flags: the eleven architectures of experiment 1 before the two flags. */
export const OLD_ELEVEN: Architecture[] = [preset("a_manual"), preset("b_lims_lite"), C, ...EIGHT.map((f) => ablate(C, f))];

const staff = loadProfile(lookup("staff", "experienced"), "staff").params;
const evaluation = evaluationSettings(readJson("scenarios", "evaluation", "default.json"));
const scenario = configOf("default", { settings: SMALL });
const REVIEW = { timing: "next_shift_start" as const, reject_also: [] as string[] };

/** A recorded value with the two new flag keys removed from its architecture: what must stay byte-identical with no break-out event. */
export const withoutNewFlags = <T extends { architecture: { flags: object } }>(ds: T): T => {
  const copy = structuredClone(ds);
  for (const k of NEW_FLAGS) delete (copy.architecture.flags as Record<string, boolean>)[k];
  return copy;
};

/** The small default scenario, seed 1, recorded and evaluated under the given architectures (no break-out block, so no break-out event). */
export const seedOneOf = (archs: readonly Architecture[]): { truth: ScenarioRun; out: SeedOutput } => {
  const truth = runScenario({ ...scenario, seed: 1 });
  const out = runSeed(seedInputFromRun(truth, {
    scenario_id: scenario.scenario_id, staff, evaluation, architectures: archs, days: scenario.process.horizon_s / 86400,
    review: { roster: rosterOf(scenario.sampling), timing: REVIEW.timing, reject_also: REVIEW.reject_also },
  }));
  return { truth, out };
};

/** One dataset hash per architecture for seed 1 (the new flag keys removed), the truth hash, and per seed of [1, 2] the cells and the report block of each. */
export const pinHashes = async (archs: readonly Architecture[] = OLD_ELEVEN): Promise<Record<string, string>> => {
  const out: Record<string, string> = {};
  const { truth: run, out: seedOut } = seedOneOf(archs);
  out["truth_seed_1"] = await logHash(run.events);
  out["key_seed_1"] = await logHash([seedOut.key_text]);
  for (const a of archs) out[`dataset_seed_1_${a.id}`] = await logHash([withoutNewFlags(seedOut.datasets[a.id] as never)]);
  const open = await runOpenLoop({ scenario, seeds: [1, 2], staff, evaluation, architectures: archs, review: REVIEW });
  for (const o of open.outcomes) for (const c of o.cells) out[`cell_seed_${o.seed}_${c.architecture}`] = await logHash([c]);
  const report = buildReport(open, { experiment_id: "pin", min_seeds: 20, ablations_of: "c_context" });
  for (const b of report.architectures) out[`block_${b.id}`] = await logHash([b]);
  return out;
};
